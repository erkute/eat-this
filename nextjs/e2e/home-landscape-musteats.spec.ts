import {test,expect} from '@playwright/test';
import {CONSENT_VERSION} from '../lib/consent';
for(const width of [667,844]) for(const motion of ['no-preference','reduce'] as const) test(`home Must Eats deal completes at ${width} (${motion})`,async({page,context,baseURL})=>{
 await context.addCookies([{name:'cookieConsent',value:`declined.${CONSENT_VERSION}`,url:baseURL!}]);
 await page.setViewportSize({width,height:390});
 await page.emulateMedia({reducedMotion:motion});
 await page.goto('/');
 const section=page.locator('[data-hub-musteats]');
 if(motion==='no-preference') await expect(section.locator('[data-deal-back]').first()).toBeAttached();
 await section.locator('ul').scrollIntoViewIfNeeded();
 await expect(section.locator('[data-deal-back]')).toHaveCount(0);
 const card=section.locator('[data-stack-photo]').first();
 expect((await card.boundingBox())!.height).toBeLessThan(220);
 await page.screenshot({path:`/tmp/eat-this-home-landscape-musteats-${width}-${motion}.png`});
 await page.setViewportSize({width:390,height:844});
 await page.setViewportSize({width,height:390});
 await section.locator('ul').scrollIntoViewIfNeeded();
 await expect(section.locator('[data-deal-back]')).toHaveCount(0);
 expect((await card.boundingBox())!.height).toBeLessThan(220);
});
